    }

    buildTypes {
        release {
            signingConfig = if (hasUploadKey) {
                signingConfigs.getByName("release")
            } else {
                logger.warn("android/key.properties not found: signing the release build with the debug key. Play rejects it.")
                signingConfigs.getByName("debug")
            }
        }
    }
